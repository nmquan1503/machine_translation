html_symbol_to_entity = {html.unescape(e): e for e in html_entities}

def _extract_entities(text):
    words = text.split()
    words = [w for w in words if any(c.isupper() for c in w)]
    words

def _up_text(text: str):
    text = text[0].upper() + text[1:]
    return text

def _process_sample(gen_text: str, src_text: str):
    for symbol, entity in html_symbol_to_entity.values():
        gen_text = gen_text.replace(symbol, entity)

    entities = _extract_entities(src_text)
    for e in entities:
        gen_text = re.sub(rf"\b{e.lower()}\b", e, gen_text)
    
    tokens = gen_text.split()
    for i in range(len(tokens)):
        if i == 0 or tokens[i - 1] in (".", "!", "?"):
            tokens[i] = _up_text(tokens[i])
    
    return " ".join(tokens)

def postprocess_texts(gen_texts: List[str], src_texts: List[str]):
    return [_process_sample(g, s) for g, s in zip(gen_texts, src_texts)]